import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11','--enable-gpu','--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: 412, height: 892 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
const p = await ctx.newPage();
p.on('console', m => { if (m.type()==='error') console.log(m.type(), m.text().slice(0,400)); });
p.on('pageerror', e => console.log('PAGEERROR', e.message.slice(0,600)));
await p.goto('http://localhost:5173/?uy=P0003&fps'); await p.waitForTimeout(5000);
await p.screenshot({ path: out+'/m1.png' });
await p.getByText('Shaharga kirish').click(); await p.waitForTimeout(2500);
await p.screenshot({ path: out+'/m2.png' });
await p.getByRole('button',{name:'Yopish'}).click(); await p.waitForTimeout(800);
await p.screenshot({ path: out+'/m3.png' });
await p.getByRole('button',{name:'Menyu'}).click(); await p.waitForTimeout(700);
await p.screenshot({ path: out+'/m4.png' });
await p.getByRole('button',{name:'Xarita'}).last().click(); await p.waitForTimeout(900);
await p.screenshot({ path: out+'/m5.png' });
await b.close();
